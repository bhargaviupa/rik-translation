#!/usr/bin/env python3
"""Remove the stored IAST runs under Saṃhitā and Pada blocks of an English file.

Decision (user, Nov 11 2026): the IAST layer of verse blocks is derived data; it is made at print time from the Devanagari
(`publish/volbook.py` add_block_iast -> `publish/tools/translit/add_iast.py`), not stored in volN's English file.  Bhāṣya blocks never get it.

  python3 tools/rv/strip_iast.py N            # strip volN/Rigveda_Samhita_VolN_English_Translation.md in place
  python3 tools/rv/strip_iast.py N --dry-run  # only count

Only an IAST run (blockquote lines `> *…*`, no Indic script) that follows a Devanagari block under a Saṃhitā/Pada label AND has as many
lines as the block is removed, so what is removed is exactly what the build regenerates.  Every run whose text differs from the
regeneration (hand-typed, old-tool variant) is listed in volN/review/iast_stripped_differing.tsv before it goes.  Nothing else changes.
Idempotent.  Run it once after a volume's last window (pipeline volumes with "iast_blocks": "build" in volcfg.json never store the runs).
"""
import re, sys, os, unicodedata
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'publish', 'tools', 'translit'))
from add_iast import deva_to_iast, norm, process, DEV
LABELS = ('संहितापाठः', 'पदपाठः')
INDIC = re.compile('[ऀ-ॿಀ-೿]')

def strip(lines):
    out, i, lab, gone, differing = [], 0, '', 0, []
    while i < len(lines):
        L = lines[i]
        if L.strip() and not L.startswith('>'): lab = L
        if L.startswith('>') and DEV.search(L) and not L.startswith('> *'):
            D = []
            while i < len(lines) and lines[i].startswith('>') and DEV.search(lines[i]) and not lines[i].startswith('> *'):
                D.append(lines[i]); out.append(lines[i]); i += 1
            if any(k in lab for k in LABELS):
                j = i
                while j < len(lines) and not lines[j].strip(): j += 1
                I = []
                while j < len(lines) and lines[j].startswith('> *') and not INDIC.search(lines[j]): I.append(lines[j]); j += 1
                if I and len(I) == len(D):
                    for d, t in zip(D, I):
                        want = norm(deva_to_iast(d.lstrip('> ').strip().replace('[?]', '')))
                        have = norm(t.lstrip('> ').strip('* '))
                        if want != have.replace('[?]', '').replace('?', ''): differing.append((len(out), d.lstrip('> ').strip(), t.lstrip('> ').strip('* ')))
                    gone += len(I); i = j
                    while i < len(lines) and not lines[i].strip(): i += 1      # blank lines around the run go with it; one is put back
                    out.append('')
            continue
        out.append(L); i += 1
    return out, gone, differing

if __name__ == '__main__':
    if len(sys.argv) < 2: sys.exit(__doc__)
    n = sys.argv[1]
    f = os.path.join(ROOT, f'vol{n}', f'Rigveda_Samhita_Vol{n}_English_Translation.md')
    lines = open(f, encoding='utf-8').read().split('\n')
    new, gone, diff = strip(lines)
    # the build must give the same lines back for everything that is not listed as differing
    back = process(new, LABELS)
    print(f'Vol {n}: IAST lines removed {gone}; differing from the regeneration {len(diff)}; regenerated by the build {sum(1 for x in back if x.startswith("> *")) - sum(1 for x in new if x.startswith("> *"))}')
    if '--dry-run' in sys.argv: sys.exit(0)
    if diff:
        os.makedirs(os.path.join(ROOT, f'vol{n}', 'review'), exist_ok=True)
        with open(os.path.join(ROOT, f'vol{n}', 'review', 'iast_stripped_differing.tsv'), 'w', encoding='utf-8') as g:
            g.write('line_in_new_file\tdevanagari\tstored_iast_removed\n')
            for k, d, t in diff: g.write(f'{k}\t{d}\t{t}\n')
    open(f, 'w', encoding='utf-8').write('\n'.join(new))
